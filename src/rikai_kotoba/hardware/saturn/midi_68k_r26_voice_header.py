"""C header renderer for the validated R26 16-slot R25-style voice ledger."""

from __future__ import annotations

from . import midi_68k_r25_resident_audio_service as _r25
from .midi_68k_r26_resident_audio_service import (
    SATURN_MIDI_68K_R26_AUDIO_OWNERSHIP_END,
    SATURN_MIDI_68K_R26_MIXER_TABLE_ADDRESS,
    SATURN_MIDI_68K_R26_OWNED_SLOTS,
    SATURN_MIDI_68K_R26_VOICE_STATE_ADDRESS,
    SATURN_MIDI_68K_R26_VOICE_STATE_BYTES,
)


def render_srk_saturn_midi_68k_r26_voice_header() -> str:
    values = {
        "VOICE_STATE_ADDRESS": SATURN_MIDI_68K_R26_VOICE_STATE_ADDRESS,
        "VOICE_STATE_BYTES": SATURN_MIDI_68K_R26_VOICE_STATE_BYTES,
        "MIXER_TABLE_ADDRESS": SATURN_MIDI_68K_R26_MIXER_TABLE_ADDRESS,
        "AUDIO_OWNERSHIP_END": SATURN_MIDI_68K_R26_AUDIO_OWNERSHIP_END,
    }
    words = {
        "VOICE_KEY_ON_COUNT_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_KEY_ON_COUNT_WORD,
        "VOICE_KEY_OFF_COUNT_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_KEY_OFF_COUNT_WORD,
        "VOICE_BUSY_COUNT_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_BUSY_COUNT_WORD,
        "VOICE_HELD_COUNT_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_HELD_COUNT_WORD,
        "VOICE_RELEASING_COUNT_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_RELEASING_COUNT_WORD,
        "VOICE_OWNED_COUNT_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_OWNED_COUNT_WORD,
        "VOICE_PEAK_HELD_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_PEAK_HELD_WORD,
        "VOICE_PEAK_RELEASING_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_PEAK_RELEASING_WORD,
        "VOICE_PEAK_OWNED_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_PEAK_OWNED_WORD,
        "VOICE_RELEASE_STARTED_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_RELEASE_STARTED_WORD,
        "VOICE_RELEASE_COMPLETED_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_RELEASE_COMPLETED_WORD,
        "VOICE_RELEASE_CANCELLED_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_RELEASE_CANCELLED_WORD,
        "VOICE_RETRIGGER_COUNT_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_RETRIGGER_COUNT_WORD,
        "VOICE_LAST_ERROR_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_LAST_ERROR_WORD,
        "VOICE_RR_WORD": _r25.SATURN_MIDI_68K_R25_VOICE_RR_WORD,
    }
    lines = [
        "#ifndef SRK_SATURN_MIDI_68K_R26_VOICE_STATE_H",
        "#define SRK_SATURN_MIDI_68K_R26_VOICE_STATE_H",
        "",
    ]
    lines.extend(f"#define SRK_MIDI_68K_R26_{name} 0x{value:08X}UL" for name, value in values.items())
    lines.append(f"#define SRK_MIDI_68K_R26_OWNED_SLOTS {SATURN_MIDI_68K_R26_OWNED_SLOTS}u")
    lines.extend(f"#define SRK_MIDI_68K_R26_{name} {value}u" for name, value in words.items())
    lines.extend(("", "#endif", ""))
    return "\n".join(lines)
